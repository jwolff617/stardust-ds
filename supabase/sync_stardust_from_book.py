"""Write supabase/migrations/<n>_stardust_book_sync.sql from the Stardust book.

Run from the UrbanWolfStudio root:
  python apps/stardust-ds/supabase/sync_stardust_from_book.py 0039
Every book word is added or updated in the Stardust dictionary. Nothing is
deleted. Part of speech and position scores on existing rows are kept.
"""
import re, sys

BOOK = "books/stardust-dictionary/STARDUST_Dictionary_First_Edition.md"
# Book name -> app term name, where the app already uses a shorter name.
RENAME = {"The Spark": "Spark", "The River": "River"}

num = sys.argv[1]
words = []
for line in open(BOOK, encoding="utf-8"):
    m = re.match(r"^\*\*([^*]+)\*\* — (.*)", line.rstrip("\n"))
    if m:
        name = RENAME.get(m.group(1).strip(), m.group(1).strip())
        body = m.group(2).strip()
        words.append((name, body))

q = lambda s: "'" + s.replace("'", "''") + "'"
rows = ",\n".join(f"  ({q(n)}, {q(b)})" for n, b in words)
names = ",\n".join(f"  ({q(n)})" for n, _ in words)
sql = f"""-- Stardust book sync ({len(words)} words), generated by
-- supabase/sync_stardust_from_book.py from
-- books/stardust-dictionary/STARDUST_Dictionary_First_Edition.md.
-- Adds every book word to the Stardust dictionary and replaces older
-- definitions with the book's. Deletes nothing. Existing rows keep their
-- part of speech and position scores; new rows are nouns. Idempotent.

insert into terms (name) values
{names}
on conflict (name) do nothing;

insert into definitions (term_id, dictionary_id, body, part_of_speech)
select t.id, d.id, b.body, 'noun'
from (values
{rows}
) as b(name, body)
join terms t on t.name = b.name
join dictionaries d on d.address = 'stardust'
on conflict (term_id, dictionary_id) do update set body = excluded.body;
"""
out = f"apps/stardust-ds/supabase/migrations/{num}_stardust_book_sync.sql"
open(out, "w", encoding="utf-8", newline="\n").write(sql)
print(out, len(words), "words")
